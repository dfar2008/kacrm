// Keep formulas in sync with src/theme/schemes.ts. Both modes preserve each hue.
import { writeFileSync } from "node:fs";

let out = "/* AUTO-GENERATED by scripts/gen-themes.mjs. */\n";
for (let i = 0; i < 35; i++) {
  const hue = Math.round((174 + i * (360 / 35)) % 360);
  for (const mode of ["dark", "light"]) {
    const light = mode === "light";
    const accent = i === 0
      ? (light ? "#08786E" : "#3FE0D0")
      : `oklch(${light ? 0.46 : 0.76} ${light ? 0.11 : 0.12} ${hue})`;
    const secondary = i === 0
      ? (light ? "#6556C7" : "#9C8CFF")
      : `oklch(${light ? 0.48 : 0.80} 0.10 ${(hue + 40) % 360})`;
    const selector = `html[data-theme="s${i + 1}"]${light ? '[data-mode="light"]' : ""}`;
    out += `${selector} {\n  --scheme-hue: ${hue};\n  --accent: ${accent};\n  --accent-2: ${secondary};\n  --fg-on-accent: ${light ? "#ffffff" : "#071218"};\n}\n`;
  }
}
writeFileSync(new URL("../src/theme/themes.css", import.meta.url), out);
console.log("wrote src/theme/themes.css (35 schemes, dark/light accents)");
