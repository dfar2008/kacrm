// frontend/scripts/gen-themes.mjs  —— 一次性生成 themes.css
import { writeFileSync } from "node:fs";

// ── 配色生成:OKLCH 感知均匀色彩空间 ──────────────────────────────
// 旧版用 hsl(hue 68% 58%):同样的 S/L 在不同色相下【感知亮度差很大】——
// 黄/绿系刺眼发亮、蓝/紫系深沉,35 套主题质感参差,黄色按钮像廉价霓虹。
// 改用 OKLCH(L=感知亮度,C=彩度,H=色相):固定 L+C → 所有色相呈【同等浓郁
// 的宝石色】,酸黄消失,整盘像精心调过。超出 sRGB 的彩度浏览器自动 gamut-map。
//
// 填充色(按钮 bg)取 L=0.56:够深,白字处处可读(OKLCH 同 L → 各色相白字
// 对比度一致,一个能读=全部能读);accent-2(伴生/浅调)取 L=0.70 更亮。
const FILL_L = 0.56, FILL_C = 0.15;   // accent  —— 实心按钮/高亮填充
const A2_L = 0.70, A2_C = 0.13;       // accent-2 —— 链接/标签/次强调

let out = "/* AUTO-GENERATED by scripts/gen-themes.mjs — 编辑公式后重跑 */\n" +
  "/* 每套方案只定义【身份】:色相 + accent(OKLCH) + accent 上的前景色。\n" +
  "   表面色/侧栏深浅由模式( :root = 深色;html[data-mode=light] = 浅色 )\n" +
  "   统一推导,所以同一套 accent 在深/浅两种模式下都能复用。 */\n";
for (let i = 0; i < 35; i++) {
  const hue = Math.round((174 + i * (360/35)) % 360);
  // s1 = 品牌默认(青 #3FE0D0 / 紫 #9C8CFF),硬复刻 :root,像素一致。
  if (i === 0) {
    out += `html[data-theme="s1"] {\n` +
      `  --scheme-hue: 174;\n` +
      `  --accent: #3FE0D0;\n` +
      `  --accent-2: #9C8CFF;\n` +
      `  --fg-on-accent: #06121a;\n}\n`;
    continue;
  }
  const accent  = `oklch(${FILL_L} ${FILL_C} ${hue})`;
  const accent2 = `oklch(${A2_L} ${A2_C} ${(hue+40)%360})`;
  out += `html[data-theme="s${i+1}"] {\n` +
    `  --scheme-hue: ${hue};\n` +
    `  --accent: ${accent};\n` +
    `  --accent-2: ${accent2};\n` +
    // L 统一为 0.56 的中调宝石色 —— 白字对比一致达标,无需按色相分叉。
    `  --fg-on-accent: #ffffff;\n}\n`;
}
writeFileSync(new URL("../src/theme/themes.css", import.meta.url), out);
console.log("wrote src/theme/themes.css (35 schemes, OKLCH)");
